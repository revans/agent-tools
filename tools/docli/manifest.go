// The manifest is a RECORD of what docli set up, for people, agents and Kamal's config. It is never used to
// decide what may be deleted: that comes from the docli:managed tag (or the docli- name prefix) on the account.

const defaultManifestRel = "config/deploys/manifest.yml"

// ManifestEntry is what a resource kind provides so the writer can store it. DNS records and managed
// databases (milestone 2) add their own entry types; the writer does not change.
type ManifestEntry interface {
	Section() string // the key under resources:, e.g. "droplets"
	EntryID() string
}

// sectionOrder is the order sections are written in; unknown sections follow, alphabetically.
var sectionOrder = []string{"droplets", "vpcs", "firewalls", "ssh_keys", "databases", "domains", "projects", "volumes", "reserved_ips", "load_balancers", "spaces_buckets", "spaces_keys"}

// accountSections are rebuilt from the account by `manifest refresh`. Domains are not: the account cannot say
// which domains or records docli created, so refresh only updates and prunes the ones the file already lists.
var accountSections = []string{"droplets", "vpcs", "firewalls", "ssh_keys", "databases", "projects", "volumes", "load_balancers", "spaces_keys"}

func manifestHeader() string {
	return fmt.Sprintf(`# DigitalOcean manifest, generated by docli %s.
# This is a RECORD of what docli set up, so people, agents and Kamal's config can see it.
# It is NOT the authority for droplets, VPCs, firewalls, SSH keys or databases: docli decides what it may delete
# from the docli:managed tag on the DigitalOcean account (and the docli- name prefix for SSH keys, VPCs and
# firewalls), never from this file. DNS is the one exception: DigitalOcean cannot tag domains or records, so the
# domains: section is how docli knows which of them it created, and it refuses to change the rest.
# Do not put secrets here. docli never writes tokens, passwords, connection strings, user data or private keys.
# Keep it honest with: docli manifest verify   Rebuild it from the account with: docli manifest refresh
`, version)
}

// Manifest is the file as a list of sections of YAML nodes, so entries docli does not touch stay as they were.
type Manifest struct {
	sections map[string][]*yaml.Node
}

func newManifest() *Manifest { return &Manifest{sections: map[string][]*yaml.Node{}} }

type manifestDoc struct {
	Version     int       `yaml:"version"`
	GeneratedBy string    `yaml:"generated_by"`
	UpdatedAt   string    `yaml:"updated_at"`
	Resources   yaml.Node `yaml:"resources"`
}

func parseManifest(data []byte) (*Manifest, error) {
	var root yaml.Node
	if err := yaml.Unmarshal(data, &root); err != nil {
		return nil, fmt.Errorf("it is not valid YAML: %v", err)
	}
	if len(root.Content) == 0 || root.Content[0].Kind != yaml.MappingNode {
		return nil, fmt.Errorf("it is not a manifest (expected a YAML mapping)")
	}
	m := newManifest()
	top := root.Content[0]
	sawVersion := false
	for i := 0; i+1 < len(top.Content); i += 2 {
		switch top.Content[i].Value {
		case "version":
			if top.Content[i+1].Value != "1" {
				return nil, fmt.Errorf("it is manifest version %s; this docli reads version 1 only", top.Content[i+1].Value)
			}
			sawVersion = true
		case "resources":
			res := top.Content[i+1]
			if res.Kind != yaml.MappingNode {
				continue
			}
			for j := 0; j+1 < len(res.Content); j += 2 {
				m.sections[res.Content[j].Value] = res.Content[j+1].Content
			}
		}
	}
	if !sawVersion {
		return nil, fmt.Errorf("it has no version: line; not a docli manifest")
	}
	return m, nil
}

// readManifest returns (nil, os.ErrNotExist-wrapping error) when the file is missing.
func readManifest(path string) (*Manifest, []byte, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, nil, err
	}
	m, err := parseManifest(data)
	if err != nil {
		return nil, data, fmt.Errorf("%s: %v. docli will not overwrite it; move it aside or fix it", path, err)
	}
	return m, data, nil
}

func nodeID(n *yaml.Node) string {
	for i := 0; i+1 < len(n.Content); i += 2 {
		if n.Content[i].Value == "id" {
			return n.Content[i+1].Value
		}
	}
	return ""
}

func nodeField(n *yaml.Node, key string) string {
	for i := 0; i+1 < len(n.Content); i += 2 {
		if n.Content[i].Value == key {
			return n.Content[i+1].Value
		}
	}
	return ""
}

func encodeEntry(e ManifestEntry) (*yaml.Node, error) {
	n := &yaml.Node{}
	if err := n.Encode(e); err != nil {
		return nil, err
	}
	return n, nil
}

// Upsert replaces the entry with the same id in place, or appends it to its section.
func (m *Manifest) Upsert(e ManifestEntry) error {
	n, err := encodeEntry(e)
	if err != nil {
		return err
	}
	list := m.sections[e.Section()]
	for i, old := range list {
		if nodeID(old) == e.EntryID() {
			list[i] = n
			return nil
		}
	}
	m.sections[e.Section()] = append(list, n)
	return nil
}

// Remove deletes the entry with this id, reporting whether it was there.
func (m *Manifest) Remove(section, id string) bool {
	list := m.sections[section]
	for i, old := range list {
		if nodeID(old) == id {
			m.sections[section] = append(list[:i:i], list[i+1:]...)
			return true
		}
	}
	return false
}

func (m *Manifest) find(section, id string) *yaml.Node {
	for _, n := range m.sections[section] {
		if nodeID(n) == id {
			return n
		}
	}
	return nil
}

func (m *Manifest) sectionNames() []string {
	var names []string
	seen := map[string]bool{}
	for _, s := range sectionOrder {
		if len(m.sections[s]) > 0 {
			names = append(names, s)
		}
		seen[s] = true
	}
	var rest []string
	for s, l := range m.sections {
		if !seen[s] && len(l) > 0 {
			rest = append(rest, s)
		}
	}
	sort.Strings(rest)
	return append(names, rest...)
}

// Marshal writes the header and the YAML; the same input always gives the same bytes.
func (m *Manifest) Marshal(now time.Time) ([]byte, error) {
	res := &yaml.Node{Kind: yaml.MappingNode}
	for _, s := range m.sectionNames() {
		res.Content = append(res.Content,
			&yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: s},
			&yaml.Node{Kind: yaml.SequenceNode, Tag: "!!seq", Content: m.sections[s]})
	}
	if len(res.Content) == 0 {
		res.Style = yaml.FlowStyle
	}
	var buf bytes.Buffer
	buf.WriteString(manifestHeader())
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	err := enc.Encode(manifestDoc{1, "docli " + version, now.UTC().Format("2006-01-02T15:04:05Z"), *res})
	if err != nil {
		return nil, err
	}
	enc.Close()
	return buf.Bytes(), nil
}

// ---- where the file lives ----

type manifestOpts struct {
	Path string
	Skip bool
}

func addManifestFlags(fs interface {
	StringVar(*string, string, string, string)
	BoolVar(*bool, string, bool, string)
}) *manifestOpts {
	mo := &manifestOpts{}
	fs.StringVar(&mo.Path, "manifest", "", "")
	fs.BoolVar(&mo.Skip, "no-manifest", false, "")
	return mo
}

// findProjectRoot walks up from dir to the nearest directory holding .git, config/ or config/deploys/manifest.yml.
func findProjectRoot(dir string) (string, bool) {
	for d := dir; ; {
		for _, marker := range []string{".git", "config", defaultManifestRel} {
			if _, err := os.Stat(filepath.Join(d, filepath.FromSlash(marker))); err == nil {
				return d, true
			}
		}
		parent := filepath.Dir(d)
		if parent == d {
			return dir, false
		}
		d = parent
	}
}

// manifestPath returns where the manifest is and how to show that path to a person.
func (r *Run) manifestPath(mo manifestOpts) (path, display string, err error) {
	if mo.Path != "" {
		return mo.Path, mo.Path, nil
	}
	cwd, err := r.Getwd()
	if err != nil {
		return "", "", err
	}
	root, found := findProjectRoot(cwd)
	if !found {
		r.infof("no project root found (no .git or config/ above %s); using the current directory for %s", cwd, defaultManifestRel)
	}
	return filepath.Join(root, filepath.FromSlash(defaultManifestRel)), defaultManifestRel, nil
}

// atomicWriteFile writes through a temp file in the same directory and renames it into place, creating
// config/deploys/ first when it is missing. A failure leaves the old file as it was and no temp file behind.
func atomicWriteFile(path string, data []byte) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(dir, ".manifest-*.tmp")
	if err != nil {
		return err
	}
	name := tmp.Name()
	cleanup := func() { os.Remove(name) }
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		cleanup()
		return err
	}
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		cleanup()
		return err
	}
	if err := tmp.Close(); err != nil {
		cleanup()
		return err
	}
	if err := os.Chmod(name, 0o644); err != nil {
		cleanup()
		return err
	}
	if err := os.Rename(name, path); err != nil {
		cleanup()
		return err
	}
	return nil
}

// ---- updating after a change ----

// change names one resource whose entry should be brought in line with the account.
type change struct {
	Section, ID string
	// Adopt (domains only) says docli just created the domain, so the file may record it as docli's.
	Adopt bool
	// AddRecords (domains only) are ids of DNS records docli just created in the domain.
	AddRecords []int
}

// updateManifest runs after a successful change. It updates only the named entries (create, replace or
// remove) and, when firewallsChanged, the firewalls list of droplet entries already in the file. A problem
// here is a warning: the change itself already happened.
func (r *Run) updateManifest(mo manifestOpts, firewallsChanged bool, changes ...change) {
	if mo.Skip {
		return
	}
	if err := r.doUpdateManifest(mo, firewallsChanged, changes); err != nil {
		r.infof("warning: the change succeeded but the manifest was not updated: %v. Fix the cause, then run: docli manifest refresh", err)
	}
}

func (r *Run) doUpdateManifest(mo manifestOpts, firewallsChanged bool, changes []change) error {
	path, display, err := r.manifestPath(mo)
	if err != nil {
		return err
	}
	snap, err := r.loadSnapshot()
	if err != nil {
		return err
	}
	m, _, err := readManifest(path)
	existed := err == nil
	if err != nil {
		if !os.IsNotExist(err) {
			return err
		}
		m = newManifest()
	}
	snap.attach(m)
	dirty := false
	for _, c := range changes {
		if c.Section == "domains" {
			d, err := snap.applyDomainChange(m, c)
			if err != nil {
				return err
			}
			dirty = dirty || d
			continue
		}
		if c.Section == "reserved_ips" && c.Adopt {
			snap.ownIPs[c.ID] = true // docli just reserved it: the manifest is how it will remember that
		}
		if e := snap.managedEntry(c.Section, c.ID); e != nil {
			if err := m.Upsert(e); err != nil {
				return err
			}
			dirty = true
		} else if m.Remove(c.Section, c.ID) {
			dirty = true
		}
	}
	if firewallsChanged {
		for _, n := range m.sections["droplets"] {
			e := snap.managedEntry("droplets", nodeID(n))
			de, ok := e.(*dropletEntry)
			if !ok {
				continue
			}
			var cur dropletEntry
			if n.Decode(&cur) == nil && !reflect.DeepEqual(nonNil(cur.Firewalls), nonNil(de.Firewalls)) {
				fresh := &yaml.Node{}
				if err := fresh.Encode(nonNil(de.Firewalls)); err != nil {
					return err
				}
				setField(n, "firewalls", fresh)
				dirty = true
			}
		}
	}
	if !dirty || (!existed && len(m.sectionNames()) == 0) {
		return nil
	}
	data, err := m.Marshal(r.Now())
	if err != nil {
		return err
	}
	if err := r.WriteFile(path, data); err != nil {
		return err
	}
	r.infof("updated %s", display)
	return nil
}

// applyDomainChange brings one domain entry in line with the account: it adds what docli just created, drops
// records and domains that are gone, and removes the entry when docli no longer owns anything in it.
func (s *snapshot) applyDomainChange(m *Manifest, c change) (bool, error) {
	if s.denied["domains"] {
		return false, fmt.Errorf("the token cannot read domains, so the manifest entry for %s was not updated", c.ID)
	}
	o := s.own[c.ID]
	if o == nil {
		o = &ownedDomain{}
	}
	created := o.Created || c.Adopt
	ids := append(append([]int(nil), o.IDs...), c.AddRecords...)
	delete(s.records, c.ID) // the change just made is not in any cached list
	e := s.buildDomainEntry(c.ID, created, ids)
	if e == nil || (!created && len(e.Records) == 0) {
		return m.Remove("domains", c.ID), nil
	}
	if err := m.Upsert(e); err != nil {
		return false, err
	}
	return true, nil
}

// refreshDomains updates and prunes the domain entries already in the file; it never adds one.
func (m *Manifest) refreshDomains(s *snapshot) error {
	if s.denied["domains"] {
		return nil
	}
	old := m.sections["domains"]
	m.sections["domains"] = nil
	for _, n := range old {
		id := nodeID(n)
		if e, _ := s.entry("domains", id); e != nil {
			if de := e.(*domainEntry); de.CreatedByDocli || len(de.Records) > 0 {
				if err := m.Upsert(e); err != nil {
					return err
				}
			}
		}
	}
	return nil
}

func setField(n *yaml.Node, key string, val *yaml.Node) {
	for i := 0; i+1 < len(n.Content); i += 2 {
		if n.Content[i].Value == key {
			n.Content[i+1] = val
			return
		}
	}
	n.Content = append(n.Content, &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: key}, val)
}

// entryMap decodes an entry node to plain values, for comparing a file entry with the account.
func entryMap(n *yaml.Node) map[string]any {
	m := map[string]any{}
	n.Decode(&m)
	return m
}

func entryToMap(e ManifestEntry) map[string]any {
	n, err := encodeEntry(e)
	if err != nil {
		return nil
	}
	return entryMap(n)
}

// diffMaps lists the fields that differ, file value first.
func diffMaps(file, acct map[string]any) []string {
	keys := map[string]bool{}
	for k := range file {
		keys[k] = true
	}
	for k := range acct {
		keys[k] = true
	}
	var sorted []string
	for k := range keys {
		sorted = append(sorted, k)
	}
	sort.Strings(sorted)
	var out []string
	for _, k := range sorted {
		if !reflect.DeepEqual(normalizeAny(file[k]), normalizeAny(acct[k])) {
			out = append(out, fmt.Sprintf("%s: file has %v, account has %v", k, show(file[k]), show(acct[k])))
		}
	}
	return out
}

func normalizeAny(v any) any {
	if l, ok := v.([]any); ok && len(l) == 0 {
		return nil
	}
	return v
}

func show(v any) string {
	if v == nil {
		return "nothing"
	}
	if s, ok := v.(string); ok {
		return fmt.Sprintf("%q", s)
	}
	return fmt.Sprint(v)
}

func stripStamps(b []byte) string {
	var keep []string
	for _, l := range strings.Split(string(b), "\n") {
		if strings.HasPrefix(l, "updated_at:") || strings.HasPrefix(l, "generated_by:") || strings.HasPrefix(l, "# DigitalOcean manifest") {
			continue
		}
		keep = append(keep, l)
	}
	return strings.Join(keep, "\n")
}

// lineDiff is a small line-by-line diff (longest common subsequence); manifests are short.
func lineDiff(a, b string) []string {
	x, y := strings.Split(strings.TrimRight(a, "\n"), "\n"), strings.Split(strings.TrimRight(b, "\n"), "\n")
	n, m := len(x), len(y)
	lcs := make([][]int, n+1)
	for i := range lcs {
		lcs[i] = make([]int, m+1)
	}
	for i := n - 1; i >= 0; i-- {
		for j := m - 1; j >= 0; j-- {
			if x[i] == y[j] {
				lcs[i][j] = lcs[i+1][j+1] + 1
			} else if lcs[i+1][j] >= lcs[i][j+1] {
				lcs[i][j] = lcs[i+1][j]
			} else {
				lcs[i][j] = lcs[i][j+1]
			}
		}
	}
	var out []string
	i, j := 0, 0
	for i < n && j < m {
		switch {
		case x[i] == y[j]:
			i++
			j++
		case lcs[i+1][j] >= lcs[i][j+1]:
			out = append(out, "- "+x[i])
			i++
		default:
			out = append(out, "+ "+y[j])
			j++
		}
	}
	for ; i < n; i++ {
		out = append(out, "- "+x[i])
	}
	for ; j < m; j++ {
		out = append(out, "+ "+y[j])
	}
	return out
}
