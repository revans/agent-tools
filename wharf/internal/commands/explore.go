// Explore connects to the SFTP server, walks the entire remote directory
// tree rooted at cfg.RemoteBasePath, and writes WHARF.md at the repo root
// describing where everything lives. Re-running it overwrites the file
// cleanly.
func Explore(cfg *config.Config, repoRoot string, logger *logging.Logger) error {
	logger.Step("connecting to %s:%d as %s", cfg.Host, cfg.Port, cfg.Username)
	client, err := sftpclient.Connect(cfg)
	if err != nil {
		logger.Error("connection failed: %v", err)
		return fmt.Errorf("connecting: %w", err)
	}
	defer client.Close()
	logger.Step("connected successfully")

	root := normalizeRemoteRoot(cfg.RemoteBasePath)
	logger.Step("walking remote tree from %s", root)

	entries, err := walkRemoteTree(client, root, logger)
	if err != nil {
		logger.Error("failed walking remote tree %s: %v", root, err)
		return fmt.Errorf("walking remote tree %s: %w", root, err)
	}

	fileCount, dirCount := 0, 0
	for _, e := range entries {
		if e.isDir {
			dirCount++
		} else {
			fileCount++
		}
	}

	sort.Slice(entries, func(i, j int) bool { return entries[i].relPath < entries[j].relPath })

	md := renderExploreMarkdown(cfg, root, entries, dirCount, fileCount)

	outPath := filepath.Join(repoRoot, "WHARF.md")
	logger.Step("writing %s", outPath)
	if err := os.WriteFile(outPath, []byte(md), 0o644); err != nil {
		logger.Error("failed to write %s: %v", outPath, err)
		return fmt.Errorf("writing %s: %w", outPath, err)
	}
	logger.Step("wrote %s (%d directories, %d files)", outPath, dirCount, fileCount)
	fmt.Printf("Wrote %s (%d directories, %d files)\n", outPath, dirCount, fileCount)
	return nil
}

func normalizeRemoteRoot(remoteBasePath string) string {
	root := strings.TrimRight(remoteBasePath, "/")
	if root == "" {
		root = "/"
	}
	return root
}

// --- markdown rendering ---

type treeNode struct {
	name     string
	isDir    bool
	children []*treeNode
	childIdx map[string]*treeNode
}

func newTreeRoot() *treeNode {
	return &treeNode{isDir: true, childIdx: map[string]*treeNode{}}
}

func (n *treeNode) insert(relPath string, isDir bool) {
	if relPath == "" {
		return
	}
	parts := strings.Split(relPath, "/")
	cur := n
	for i, part := range parts {
		last := i == len(parts)-1
		child, ok := cur.childIdx[part]
		if !ok {
			child = &treeNode{name: part, isDir: !last || isDir}
			if child.isDir {
				child.childIdx = map[string]*treeNode{}
			}
			cur.childIdx[part] = child
			cur.children = append(cur.children, child)
		}
		cur = child
	}
}

func (n *treeNode) render(prefix string, sb *strings.Builder) {
	sort.Slice(n.children, func(i, j int) bool {
		a, b := n.children[i], n.children[j]
		if a.isDir != b.isDir {
			return a.isDir
		}
		return a.name < b.name
	})
	for _, c := range n.children {
		label := c.name
		if c.isDir {
			label += "/"
		}
		sb.WriteString(prefix + "- " + label + "\n")
		if c.isDir {
			c.render(prefix+"  ", sb)
		}
	}
}

func renderExploreMarkdown(cfg *config.Config, root string, entries []remoteEntry, dirCount, fileCount int) string {
	var sb strings.Builder

	sb.WriteString("# WHARF.md — Remote Server Structure\n\n")
	sb.WriteString(fmt.Sprintf("Generated by `wharf explore` on %s. Do not hand-edit — re-run `wharf explore` to regenerate; it overwrites this file completely.\n\n", time.Now().Format(time.RFC1123)))
	sb.WriteString("This document describes the **remote SFTP layout** for static sites, so anyone (or any LLM) working on the site can see where content lives on the server before uploading anything — without needing SFTP access themselves.\n\n")
	sb.WriteString(fmt.Sprintf("- **Host:** `%s`\n", cfg.Host))
	sb.WriteString(fmt.Sprintf("- **Remote base path:** `%s`\n", root))
	sb.WriteString("- **Path mirroring rule:** a local file at repo-relative path `X` uploads to `<remote base path>/X`. All paths in this document are shown relative to the remote base path above.\n")
	sb.WriteString(fmt.Sprintf("- **Total directories:** %d\n", dirCount))
	sb.WriteString(fmt.Sprintf("- **Total files:** %d\n\n", fileCount))

	sb.WriteString("## Directory Tree\n\n")
	sb.WriteString("```\n")
	tree := newTreeRoot()
	for _, e := range entries {
		tree.insert(e.relPath, e.isDir)
	}
	tree.render("", &sb)
	sb.WriteString("```\n\n")

	sb.WriteString("## File Counts Per Directory\n\n")
	sb.WriteString("Counts are files directly inside each directory (not recursive).\n\n")
	sb.WriteString("| Directory | Files |\n|---|---|\n")
	counts := map[string]int{}
	for _, e := range entries {
		if e.isDir {
			continue
		}
		dir := path.Dir(e.relPath)
		if dir == "." {
			dir = "(remote base path root)"
		}
		counts[dir]++
	}
	var dirs []string
	for d := range counts {
		dirs = append(dirs, d)
	}
	sort.Strings(dirs)
	for _, d := range dirs {
		sb.WriteString(fmt.Sprintf("| `%s` | %d |\n", d, counts[d]))
	}
	sb.WriteString("\n")

	sb.WriteString("## Full File Listing\n\n")
	sb.WriteString("Every remote file path (relative to the remote base path), for quick \"where does X go\" lookup.\n\n")
	for _, e := range entries {
		if e.isDir {
			continue
		}
		sb.WriteString(fmt.Sprintf("- `%s` (%d bytes)\n", e.relPath, e.size))
	}
	sb.WriteString("\n")

	return sb.String()
}
