func TestManifestNotTouchedByDryRunRefusalOrFailure(t *testing.T) {
	e := newEnv(t)
	buildScenario(t, e)
	before := e.readManifest()
	files := func() []string {
		var out []string
		filepath.Walk(e.project, func(p string, info os.FileInfo, err error) error {
			if err == nil && !strings.Contains(p, ".git") {
				out = append(out, p)
			}
			return nil
		})
		return out
	}
	list := strings.Join(files(), "\n")
	check := func(what string) {
		t.Helper()
		if e.readManifest() != before {
			t.Fatalf("%s changed the manifest", what)
		}
		if strings.Join(files(), "\n") != list {
			t.Fatalf("%s left files behind", what)
		}
		notContain(t, e.errb.String(), "updated config")
	}
	e.mustRun(withArgs("--dry-run")...)
	check("create --dry-run")
	e.mustRun("firewall", "add-rule", "web", "in:tcp:9:from=1.2.3.4", "--dry-run")
	check("add-rule --dry-run")
	e.mustRun("droplet", "delete", "web-1", "--dry-run")
	check("delete --dry-run")
	e.tty(false)
	e.expect(exitRefused, withArgs()...)
	check("a create without confirmation")
	e.tty(true)
	e.stdin("n\n")
	e.expect(exitRefused, "firewall", "delete", "web")
	check("a declined delete")
	e.expect(exitRefused, "droplet", "delete", "legacy-db", "--yes", "--confirm-name", "legacy-db")
	check("an ownership refusal")
	e.expect(exitRefused, "vpc", "delete", "net", "--yes") // has members
	check("a vpc delete that has members")
	e.fake.Fails["POST /v2/droplets"] = []fakeFail{{Status: 500}}
	e.expect(exitError, withArgs("--yes")...)
	check("a failed create")
	e.fake.Fails["DELETE /v2/firewalls/"+e.fake.Firewalls[1].ID] = []fakeFail{{Status: 500}}
	e.expect(exitError, "firewall", "delete", "web", "--yes")
	check("a failed delete")
}

