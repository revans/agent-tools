func TestAtomicWrite(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "a", "b", "manifest.yml")
	if err := atomicWriteFile(path, []byte("one")); err != nil {
		t.Fatal(err)
	}
	if err := atomicWriteFile(path, []byte("two")); err != nil {
		t.Fatal(err)
	}
	if b, _ := os.ReadFile(path); string(b) != "two" {
		t.Fatal(string(b))
	}
	entries, _ := os.ReadDir(filepath.Dir(path))
	if len(entries) != 1 {
		t.Fatalf("temp files left behind: %v", entries)
	}
	// the final rename fails (the target is a non-empty directory): the temp file is cleaned up
	bad := filepath.Join(dir, "target")
	os.MkdirAll(filepath.Join(bad, "inner"), 0o755)
	if err := atomicWriteFile(bad, []byte("x")); err == nil {
		t.Fatal("expected an error")
	}
	entries, _ = os.ReadDir(dir)
	for _, en := range entries {
		if strings.HasPrefix(en.Name(), ".manifest-") {
			t.Fatalf("partial file left behind: %s", en.Name())
		}
	}
}

