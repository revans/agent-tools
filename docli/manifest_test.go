func TestManifestVerifyExitCodes(t *testing.T) {
	type verifyDoc struct {
		Path        string     `json:"path"`
		InSync      bool       `json:"in_sync"`
		Differences []diffItem `json:"differences"`
	}
	e := newEnv(t)
	e.expect(exitError, "manifest", "verify")
	contain(t, e.errb.String(), "no manifest at")
	buildScenario(t, e)
	before := e.readManifest()
	e.mustRun("manifest", "verify")
	contain(t, e.out.String(), "matches the account")
	e.mustRun("manifest", "verify", "--json")
	var v verifyDoc
	jsonOut(t, e, &v)
	if !v.InSync || len(v.Differences) != 0 {
		t.Fatalf("%+v", v)
	}

	// 1. drift in a field
	e.fake.droplet(5003).Status = "off"
	e.expect(exitError, "manifest", "verify", "--json")
	jsonOut(t, e, &v)
	if v.InSync || len(v.Differences) != 1 || v.Differences[0].Kind != "drift" || !strings.Contains(v.Differences[0].Detail, "status") {
		t.Fatalf("%+v", v)
	}
	e.expect(exitError, "manifest", "verify")
	contain(t, e.out.String(), `file has "active", account has "off"`)
	e.fake.droplet(5003).Status = "active"
	e.mustRun("manifest", "verify")

	// 2. a managed resource missing from the file
	e.fake.addDroplet(&godo.Droplet{ID: 3003, Name: "stray", Status: "active", Tags: []string{"docli:managed"}}, "s-1vcpu-1gb", "nyc3", "10.0.0.9", "203.0.113.9")
	e.expect(exitError, "manifest", "verify", "--json")
	jsonOut(t, e, &v)
	if len(v.Differences) != 1 || v.Differences[0].Kind != "missing_in_file" || v.Differences[0].Name != "stray" {
		t.Fatalf("%+v", v)
	}
	// unmanaged resources are not expected in the file
	e.fake.Droplets = e.fake.Droplets[:len(e.fake.Droplets)-1]
	e.mustRun("manifest", "verify")

	// 3. an entry whose resource is gone
	e.fake.Keys = e.fake.Keys[:1]
	e.expect(exitError, "manifest", "verify", "--json")
	jsonOut(t, e, &v)
	if len(v.Differences) != 1 || v.Differences[0].Kind != "missing_in_account" || v.Differences[0].Section != "ssh_keys" {
		t.Fatalf("%+v", v)
	}
	if e.readManifest() != before {
		t.Fatal("verify changed the file")
	}
	for _, m := range e.fake.Mutations() {
		if !strings.Contains(m, "/v2/") {
			t.Fatal(m)
		}
	}
	n := len(e.fake.Mutations())
	e.run("manifest", "verify")
	if len(e.fake.Mutations()) != n {
		t.Fatal("verify must only read")
	}
	// a corrupt file is reported, not overwritten
	os.WriteFile(e.manifest(), []byte("this: [is not"), 0o644)
	e.expect(exitError, "manifest", "verify")
	e.expect(exitError, "manifest", "refresh", "--yes")
	contain(t, e.errb.String(), "will not overwrite")
	if b, _ := os.ReadFile(e.manifest()); string(b) != "this: [is not" {
		t.Fatal("a file docli cannot read must be left alone")
	}
}

func TestManifestRefresh(t *testing.T) {
	e := newEnv(t)
	e.env["DOCLI_REGION"] = "nyc3"
	// resources made earlier, with --no-manifest, so the file does not know them
	e.mustRun("vpc", "create", "--name", "net", "--yes", "--no-manifest")
	e.mustRun(withArgs("--wait", "--yes", "--no-manifest")...)
	e.tty(false)
	e.expect(exitRefused, "manifest", "refresh")
	if _, err := os.Stat(e.manifest()); err == nil {
		t.Fatal("refresh wrote without confirmation")
	}
	e.mustRun("manifest", "refresh", "--dry-run")
	contain(t, e.out.String(), "Changes to config/deploys/manifest.yml")
	contain(t, e.out.String(), "+ ")
	contain(t, e.out.String(), "Dry run")
	if _, err := os.Stat(e.manifest()); err == nil {
		t.Fatal("dry run wrote the file")
	}
	e.mustRun("manifest", "refresh", "--yes")
	m := e.readManifest()
	contain(t, m, "docli-net")
	contain(t, m, "web-1")
	notContain(t, m, "legacy-db")
	notContain(t, m, "robert-laptop")
	if strings.Count(m, "ip_range:") != 1 {
		t.Fatalf("only docli VPCs belong in the file:\n%s", m)
	}
	e.mustRun("manifest", "refresh", "--yes")
	contain(t, e.out.String(), "already matches the account")
	// drift: refresh shows the diff, then fixes it
	e.fake.droplet(5002).Status = "off"
	e.fake.VPCs = e.fake.VPCs[:2] // docli-net vanished
	e.mustRun("manifest", "refresh", "--dry-run")
	contain(t, e.out.String(), `- `)
	contain(t, e.out.String(), "status: active")
	contain(t, e.out.String(), `+       status: "off"`)
	e.tty(true)
	e.stdin("n\n")
	e.expect(exitRefused, "manifest", "refresh")
	contain(t, e.readManifest(), "status: active")
	e.stdin("y\n")
	e.mustRun("manifest", "refresh")
	m = e.readManifest()
	contain(t, m, "status: \"off\"")
	notContain(t, m, "docli-net\n")
	e.mustRun("manifest", "verify")
}
