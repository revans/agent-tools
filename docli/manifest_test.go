func TestManifestUpdatesOnlyTheChangedEntry(t *testing.T) {
	e := newEnv(t)
	buildScenario(t, e)
	e.mustRun("droplet", "create", "--name", "web-2", "--size", "s-1vcpu-1gb", "--image", "ubuntu-24-04-x64", "--wait", "--yes")
	e.mustRun("droplet", "create", "--name", "web-3", "--size", "s-1vcpu-1gb", "--image", "ubuntu-24-04-x64", "--wait", "--yes")
	before := e.readManifest()
	// a rule change touches the firewall entry and nothing else
	e.mustRun("firewall", "add-rule", "web", "in:tcp:8080:from=10.50.0.0/24", "--yes")
	contain(t, e.errb.String(), "updated config/deploys/manifest.yml")
	after := e.readManifest()
	var changed []string
	for _, l := range lineDiff(before, after) {
		if !strings.Contains(l, "updated_at:") {
			changed = append(changed, l)
		}
	}
	if len(changed) != 1 || !strings.Contains(changed[0], "in:tcp:8080:from=10.50.0.0/24") || !strings.HasPrefix(changed[0], "+ ") {
		t.Fatalf("only the new rule line should differ, got %v", changed)
	}
	// deleting one droplet removes only its entry; the others keep their place and text
	e.mustRun("droplet", "delete", "web-2", "--yes", "--confirm-name", "web-2")
	final := e.readManifest()
	if strings.Contains(final, "web-2") || !strings.Contains(final, "web-1") || !strings.Contains(final, "web-3") {
		t.Fatalf("%s", final)
	}
	if strings.Index(final, "web-1") > strings.Index(final, "web-3") {
		t.Fatal("order changed")
	}
	for _, l := range lineDiff(after, final) {
		if strings.HasPrefix(l, "+ ") && !strings.Contains(l, "updated_at") && !strings.Contains(l, "firewalls") {
			t.Fatalf("unexpected addition %q", l)
		}
	}
	// header is the same
	if strings.SplitN(before, "version:", 2)[0] != strings.SplitN(final, "version:", 2)[0] {
		t.Fatal("header changed")
	}
}

