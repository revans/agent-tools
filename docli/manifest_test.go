func TestProjectRootDiscovery(t *testing.T) {
	mk := func(dirs ...string) string {
		root := t.TempDir()
		for _, d := range dirs {
			os.MkdirAll(filepath.Join(root, d), 0o755)
		}
		return root
	}
	root := mk(".git", "app/models/deep")
	if got, ok := findProjectRoot(filepath.Join(root, "app", "models", "deep")); !ok || got != root {
		t.Fatalf("%q %v", got, ok)
	}
	root = mk("config", "src/x")
	if got, ok := findProjectRoot(filepath.Join(root, "src", "x")); !ok || got != root {
		t.Fatalf("config/ marks the root: %q %v", got, ok)
	}
	root = mk("a/config/deploys", "a/b")
	os.WriteFile(filepath.Join(root, "a", "config", "deploys", "manifest.yml"), []byte("version: 1\n"), 0o644)
	if got, ok := findProjectRoot(filepath.Join(root, "a", "b")); !ok || got != filepath.Join(root, "a") {
		t.Fatalf("%q %v", got, ok)
	}
	root = mk(".git", "inner/.git", "inner/deep")
	if got, _ := findProjectRoot(filepath.Join(root, "inner", "deep")); got != filepath.Join(root, "inner") {
		t.Fatalf("the nearest marker wins, got %q", got)
	}
	// .git can be a file (worktrees, submodules)
	root = mk("sub")
	os.WriteFile(filepath.Join(root, ".git"), []byte("gitdir: elsewhere"), 0o644)
	if got, ok := findProjectRoot(filepath.Join(root, "sub")); !ok || got != root {
		t.Fatalf("%q %v", got, ok)
	}
	// nothing found: the starting directory, and the person is told
	lone := t.TempDir()
	if _, ok := findProjectRoot(lone); ok {
		t.Skip("a parent of the temp directory looks like a project; cannot test the no-root case here")
	}
	e := newEnv(t)
	e.cwd = lone
	e.mustRun(withArgs("--yes")...)
	contain(t, e.errb.String(), "no project root found")
	if _, err := os.Stat(filepath.Join(lone, "config", "deploys", "manifest.yml")); err != nil {
		t.Fatal("falls back to the current directory")
	}
}

